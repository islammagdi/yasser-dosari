export const RUBS = 240;
export const WIRD_JUZ_DURATIONS = [7, 10, 15, 30, 60] as const;

export interface WirdSegment {
  surah: number;
  from: number;
  to: number;
  /** السورة كاملة (مش محتاجين توقيت الآيات) */
  whole: boolean;
}

export interface WirdPortion {
  /** رقم اليوم في الخطة من ٠ */
  index: number;
  fromRub: number;
  toRub: number;
  /** "الجزء ٥" أو "من الجزء ١ إلى الجزء ٤" */
  label: string;
  /** "من البقرة ١٤٢ إلى البقرة ٢٥٢" */
  range: string;
  segments: WirdSegment[];
}

const juzOf = (rub: number) => Math.floor(rub / 8) + 1;

/** نصيب يوم معيّن في خطة مدتها days */
export function wirdPortion(days: number, index: number): WirdPortion {
  const fromRub = Math.floor((RUBS * index) / days);
  const toRub = Math.floor((RUBS * (index + 1)) / days) - 1;
  const [s1, a1] = RUB_STARTS[fromRub];
  // آخر آية = الآية اللي قبل بداية الربع اللي بعده
  let s2: number;
  let a2: number;
  if (toRub + 1 >= RUBS) {
    s2 = 114;
    a2 = AYAH_COUNTS[113];
  } else {
    const [ns, na] = RUB_STARTS[toRub + 1];
    if (na > 1) [s2, a2] = [ns, na - 1];
    else [s2, a2] = [ns - 1, AYAH_COUNTS[ns - 2]];
  }

  const segments: WirdSegment[] = [];
  for (let s = s1; s <= s2; s++) {
    const from = s === s1 ? a1 : 1;
    const to = s === s2 ? a2 : AYAH_COUNTS[s - 1];
    segments.push({ surah: s, from, to, whole: from === 1 && to === AYAH_COUNTS[s - 1] });
  }

  const j1 = juzOf(fromRub);
  const j2 = juzOf(toRub);
  const wholeJuz = fromRub % 8 === 0 && (toRub + 1) % 8 === 0;
  const span = toRub - fromRub + 1;
  let label: string;
  if (j1 === j2) {
    if (wholeJuz) label = `الجزء ${toArabicDigits(j1)}`;
    else if (span === 4) label = `${fromRub % 8 === 0 ? "النصف الأول" : "النصف الثاني"} من الجزء ${toArabicDigits(j1)}`;
    else label = `من الجزء ${toArabicDigits(j1)}`;
  } else if (wholeJuz && j2 === j1 + 1) label = `الجزء ${toArabicDigits(j1)} و${toArabicDigits(j2)}`;
  else label = `من الجزء ${toArabicDigits(j1)} إلى الجزء ${toArabicDigits(j2)}`;

  const range = `من ${surahName(s1)} ${toArabicDigits(a1)} إلى ${surahName(s2)} ${toArabicDigits(a2)}`;
  return { index, fromRub, toRub, label, range, segments };
}

/** نصيب اليوم كوصف للمدة: "جزء يوميًا"، "جزئين يوميًا"، "حزب يوميًا"… */
export function dailyAmountLabel(days: number): string {
  const juz = 30 / days;
  if (juz === 1) return "جزء يوميًا";
  if (juz === 2) return "جزئين يوميًا";
  if (juz === 0.5) return "حزب يوميًا";
  if (Number.isInteger(juz)) return `${toArabicDigits(juz)} أجزاء يوميًا`;
  return `حوالي ${toArabicDigits(Math.round(juz * 10) / 10)} جزء يوميًا`;
}
